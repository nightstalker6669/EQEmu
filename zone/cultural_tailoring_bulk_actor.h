inline const Requirement* Find(std::uint32_t id) noexcept {
 constexpr std::uint32_t count=sizeof(Requirements)/sizeof(Requirements[0]);
 std::uint32_t low=0,high=count;
 while(low<high) {const auto mid=low+(high-low)/2;if(Requirements[mid].recipe_id<id)low=mid+1;else high=mid;}
 return low<count && Requirements[low].recipe_id==id ? &Requirements[low] : nullptr;
}
